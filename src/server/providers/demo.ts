export function findDistrict(text: string | null): string | null {
  const t = ` ${normalizeText(text)} `;
  for (const d of Object.keys(DISTRICTS)) if (t.includes(` ${normalizeText(d)} `)) return d;
  return null;
}

function hashUnit(s: string, salt: string): number {
  const h = createHash("sha256").update(`${salt}:${s}`).digest();
  return h.readUInt32BE(0) / 0xffffffff;
}

export function haversineKm(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const R = 6371;
  const dLat = ((b.lat - a.lat) * Math.PI) / 180;
  const dLng = ((b.lng - a.lng) * Math.PI) / 180;
  const x = Math.sin(dLat / 2) ** 2 + Math.cos((a.lat * Math.PI) / 180) * Math.cos((b.lat * Math.PI) / 180) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(x));
}

const ATTR = "DEMO — synthetic data generated by NextPlace for testing. Not real research.";

export const demoGeo: GeoProvider = {
  name: "demo",
  isDemo: true,
  attribution: ATTR,
  cacheDays: 3650,
  async geocode(name, district) {
    const d = findDistrict(district) ?? findDistrict(name);
    const jitter = (salt: string) => (hashUnit(normalizeText(name), salt) - 0.5) * 0.12;
    if (d) {
      const c = DISTRICTS[d];
      return {
        status: "resolved",
        candidates: [{ label: `${name} (demo location near ${d})`, lat: c.lat + jitter("lat"), lng: c.lng + jitter("lng"), confidence: 0.7, placeRef: `demo:${d}` }],
      };
    }
    // No district information: return deterministic alternatives that the user must confirm.
    const keys = Object.keys(DISTRICTS);
    const picks = [0, 1].map((i) => keys[Math.floor(hashUnit(normalizeText(name), `pick${i}`) * keys.length)]);
    const uniq = Array.from(new Set(picks));
    return {
      status: "ambiguous",
      candidates: uniq.map((k) => ({ label: `${name} — ${k} (demo candidate)`, lat: DISTRICTS[k].lat + jitter(k), lng: DISTRICTS[k].lng + jitter(k + "x"), confidence: 0.4, placeRef: `demo:${k}` })),
    };
  },
};

export const demoRoute: RouteProvider = {
  name: "demo",
  isDemo: true,
  attribution: ATTR,
  cacheDays: 3650,
  async route(from, to, mode) {
    const straight = haversineKm(from, to);
    const km = straight * 1.35;
    const drive = (km / 40) * 60 + 8;
    if (mode === "drive")
      return { status: "ok", minutes: Math.round(drive), km: Math.round(km * 10) / 10, assumptions: "DEMO: road distance = straight-line × 1.35 at 40 km/h average + 8 min" };
    return { status: "ok", minutes: Math.round(drive * 1.7 + 20), km: Math.round(km * 10) / 10, assumptions: "DEMO: transit time = demo driving time × 1.7 + 20 min waiting. No timetable data." };
  },
};

export const demoClimate: ClimateProvider = {
  name: "demo",
  isDemo: true,
  attribution: ATTR,
  cacheDays: 3650,
  async climate(lat, lng) {
    let best = "Colombo";
    let bestD = Infinity;
    for (const [k, v] of Object.entries(DISTRICTS)) {
      const dd = haversineKm({ lat, lng }, v);
      if (dd < bestD) {
        bestD = dd;
        best = k;
      }
    }
    const c = DISTRICTS[best];
    return { status: "ok", meanTempC: c.temp, annualRainMm: c.rain, period: `DEMO synthetic values for the ${best} area` };
  },
};

